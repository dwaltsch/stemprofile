#!/usr/bin/env node
/**
 * Asset Version Stamping
 *
 * GitHub Pages caches every file for 10 minutes and the app has no build
 * step, so after a deploy a browser could combine a new module with stale
 * cached ones (e.g. a new app.js importing an export an old share.js lacks).
 * This script gives every asset URL a content hash in index.html:
 *
 * - an import map maps each ES module (`./js/x.js`) to `./js/x.js?v=<hash>`,
 *   which also covers relative imports between modules
 * - stylesheet links and the entry <script src> get `?v=<hash>`
 * - the import map is an inline script, so its SHA-256 is added to the CSP
 *   script-src (everything else stays 'self' only)
 *
 * Usage:
 *   node scripts/stamp-assets.mjs           rewrite index.html
 *   node scripts/stamp-assets.mjs --check   exit 1 if index.html is stale
 *
 * @module scripts/stamp-assets
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MAP_START = '<!-- asset-stamp:importmap (generated by scripts/stamp-assets.mjs, do not edit) -->';
const MAP_END = '<!-- /asset-stamp:importmap -->';

/** Short content hash used as the cache-busting version. */
export function contentHash(buffer) {
  return createHash('sha256').update(buffer).digest('hex').slice(0, 10);
}

/** CSP source expression for an inline script's exact text. */
export function cspHash(text) {
  return `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`;
}

/** All ES modules under js/, as sorted repo-relative POSIX paths. */
export function listModules(root) {
  const out = [];
  const walk = dir => {
    for (const entry of readdirSync(path.join(root, dir), { withFileTypes: true })) {
      const rel = `${dir}/${entry.name}`;
      if (entry.isDirectory()) walk(rel);
      else if (entry.name.endsWith('.js')) out.push(rel);
    }
  };
  walk('js');
  return out.sort();
}

/** Import map text mapping every module to its content-hashed URL. */
export function buildImportMapText(root) {
  const imports = {};
  for (const rel of listModules(root)) {
    imports[`./${rel}`] = `./${rel}?v=${contentHash(readFileSync(path.join(root, rel)))}`;
  }
  return '\n' + JSON.stringify({ imports }, null, 2) + '\n  ';
}

/**
 * Returns index.html with all asset versions, the import map and the CSP hash brought up to date.
 *
 * @param {string} html - Current index.html
 * @param {string} root - Repository root
 * @returns {string} Stamped index.html
 */
export function stampIndexHtml(html, root) {
  const version = rel => contentHash(readFileSync(path.join(root, rel)));

  // 1. Stylesheets and the entry module script
  let out = html.replace(/(<link rel="stylesheet" href=")(css\/[\w-]+\.css)(?:\?v=[\w]+)?(")/g,
    (_, pre, rel, post) => `${pre}${rel}?v=${version(rel)}${post}`);
  out = out.replace(/(<script type="module" src=")(js\/app\.js)(?:\?v=[\w]+)?(")/,
    (_, pre, rel, post) => `${pre}${rel}?v=${version(rel)}${post}`);

  // 2. Import map block (inserted before the entry script on first run)
  const mapText = buildImportMapText(root);
  const block = `${MAP_START}\n  <script type="importmap">${mapText}</script>\n  ${MAP_END}`;
  const start = out.indexOf(MAP_START);
  if (start !== -1) {
    const end = out.indexOf(MAP_END, start);
    if (end === -1) throw new Error('index.html: import map start marker without end marker');
    out = out.slice(0, start) + block + out.slice(end + MAP_END.length);
  } else {
    const entry = out.indexOf('<script type="module"');
    if (entry === -1) throw new Error('index.html: entry <script type="module"> not found');
    out = out.slice(0, entry) + block + '\n  ' + out.slice(entry);
  }

  // 3. CSP: script-src 'self' plus exactly the import map's hash
  out = out.replace(/script-src 'self'(?: 'sha256-[A-Za-z0-9+/=]+')*/, `script-src 'self' ${cspHash(mapText)}`);
  return out;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const file = path.join(root, 'index.html');
  const html = readFileSync(file, 'utf8');
  const stamped = stampIndexHtml(html, root);
  if (process.argv.includes('--check')) {
    if (stamped !== html) {
      console.error('index.html asset versions are stale. Run: node scripts/stamp-assets.mjs (or `just stamp`)');
      process.exit(1);
    }
    console.log('index.html asset versions are up to date.');
  } else if (stamped !== html) {
    writeFileSync(file, stamped);
    console.log(`Stamped ${listModules(root).length} modules, stylesheets and the CSP hash in index.html.`);
  } else {
    console.log('index.html already up to date.');
  }
}

#!/usr/bin/env node
/**
 * Asset Version Stamping
 *
 * GitHub Pages caches every file for 10 minutes and the app has no build
 * step, so after a deploy a browser could combine a new module with stale
 * cached ones (e.g. a new app.js importing an export an old share.js lacks).
 * This script gives every asset URL a content hash in index.html:
 *
 * - an import map maps each ES module (`./js/x.js`) to `./js/x.js?v=<hash>`,
 *   which also covers relative imports between modules
 * - stylesheet links and the entry <script src> get `?v=<hash>`
 * - the import map is an inline script, so its SHA-256 is added to the CSP
 *   script-src (everything else stays 'self' only)
 * - sw.js gets the precache list of every URL the stamped page loads, the full
 *   SHA-256 of each of those files and a cache version, so the offline copy
 *   always matches the deployed page and a tampered cache entry is never served
 *
 * Usage:
 *   node scripts/stamp-assets.mjs           rewrite index.html and sw.js
 *   node scripts/stamp-assets.mjs --check   exit 1 if either is stale
 *
 * @module scripts/stamp-assets
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MAP_START = '<!-- asset-stamp:importmap (generated by scripts/stamp-assets.mjs, do not edit) -->';
const MAP_END = '<!-- /asset-stamp:importmap -->';
const SW_START = '// asset-stamp:precache (generated by scripts/stamp-assets.mjs, do not edit)';
const SW_END = '// /asset-stamp:precache';

/** Unversioned files the offline app also needs (the page itself, icon, manifest, info page). */
export const STATIC_PRECACHE = ['./', './favicon.svg', './manifest.webmanifest', './info/', './info/info.css'];

/** Short content hash used as the cache-busting version. */
export function contentHash(buffer) {
  return createHash('sha256').update(buffer).digest('hex').slice(0, 10);
}

/** CSP source expression for an inline script's exact text. */
export function cspHash(text) {
  return `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`;
}

/** All ES modules under js/, as sorted repo-relative POSIX paths. */
export function listModules(root) {
  const out = [];
  const walk = dir => {
    for (const entry of readdirSync(path.join(root, dir), { withFileTypes: true })) {
      const rel = `${dir}/${entry.name}`;
      if (entry.isDirectory()) walk(rel);
      else if (entry.name.endsWith('.js')) out.push(rel);
    }
  };
  walk('js');
  return out.sort();
}

/** Import map text mapping every module to its content-hashed URL. */
export function buildImportMapText(root) {
  const imports = {};
  for (const rel of listModules(root)) {
    imports[`./${rel}`] = `./${rel}?v=${contentHash(readFileSync(path.join(root, rel)))}`;
  }
  return '\n' + JSON.stringify({ imports }, null, 2) + '\n  ';
}

/**
 * Returns index.html with all asset versions, the import map and the CSP hash brought up to date.
 *
 * @param {string} html - Current index.html
 * @param {string} root - Repository root
 * @returns {string} Stamped index.html
 */
export function stampIndexHtml(html, root) {
  const version = rel => contentHash(readFileSync(path.join(root, rel)));

  // 1. Stylesheets and the entry module script
  let out = html.replace(/(<link rel="stylesheet" href=")(css\/[\w-]+\.css)(?:\?v=[\w]+)?(")/g,
    (_, pre, rel, post) => `${pre}${rel}?v=${version(rel)}${post}`);
  out = out.replace(/(<script type="module" src=")(js\/app\.js)(?:\?v=[\w]+)?(")/,
    (_, pre, rel, post) => `${pre}${rel}?v=${version(rel)}${post}`);

  // 2. Import map block (inserted before the entry script on first run)
  const mapText = buildImportMapText(root);
  const block = `${MAP_START}\n  <script type="importmap">${mapText}</script>\n  ${MAP_END}`;
  const start = out.indexOf(MAP_START);
  if (start !== -1) {
    const end = out.indexOf(MAP_END, start);
    if (end === -1) throw new Error('index.html: import map start marker without end marker');
    out = out.slice(0, start) + block + out.slice(end + MAP_END.length);
  } else {
    const entry = out.indexOf('<script type="module"');
    if (entry === -1) throw new Error('index.html: entry <script type="module"> not found');
    out = out.slice(0, entry) + block + '\n  ' + out.slice(entry);
  }

  // 3. CSP: script-src 'self' plus exactly the import map's hash
  out = out.replace(/script-src 'self'(?: 'sha256-[A-Za-z0-9+/=]+')*/, `script-src 'self' ${cspHash(mapText)}`);
  return out;
}

/**
 * Every URL the stamped page loads: stylesheets, the entry script and all modules (with ?v= hashes).
 *
 * @param {string} html - Stamped index.html
 * @returns {string[]} Page-relative URLs, sorted
 */
export function listPageAssets(html) {
  const urls = new Set();
  for (const m of html.matchAll(/(?:href|src)="((?:css|js)\/[\w/-]+\.(?:css|js)\?v=[0-9a-f]{10})"/g)) urls.add(`./${m[1]}`);
  const map = html.match(/<script type="importmap">([\s\S]*?)<\/script>/);
  if (map) for (const url of Object.values(JSON.parse(map[1]).imports)) urls.add(url);
  return [...urls].sort();
}

/** Full SHA-256 (hex). The 10-character ?v= stamps are too short to resist a forged file. */
export function sha256Hex(buffer) {
  return createHash('sha256').update(buffer).digest('hex');
}

/**
 * Exact bytes the server returns for a precached URL ('./' is the stamped page itself).
 *
 * @param {string} url - Precache entry, e.g. './js/app.js?v=…' or './info/'
 * @param {string} stampedHtml - Stamped index.html
 * @param {string} root - Repository root
 * @returns {Buffer}
 */
export function precachedBytes(url, stampedHtml, root) {
  if (url === './') return Buffer.from(stampedHtml);
  const file = url.split('?')[0].replace(/\/$/, '/index.html');
  return readFileSync(path.join(root, file));
}

/**
 * Returns sw.js with its precache list, the SHA-256 of every precached file and the
 * cache version generated from the stamped page.
 * The version hashes the page itself, so any change to index.html or an asset ships a new worker.
 *
 * @param {string} sw - Current sw.js
 * @param {string} stampedHtml - Stamped index.html
 * @param {string} root - Repository root
 * @returns {string} Updated sw.js
 */
export function stampServiceWorker(sw, stampedHtml, root) {
  const precache = [...STATIC_PRECACHE, ...listPageAssets(stampedHtml)];
  const statics = STATIC_PRECACHE.filter(u => !u.endsWith('/')).map(u => readFileSync(path.join(root, u)));
  const version = contentHash(Buffer.concat([Buffer.from(stampedHtml), Buffer.from(precache.join('\n')), ...statics,
    readFileSync(path.join(root, 'info', 'index.html'))]));
  const integrity = {};
  for (const url of precache) integrity[url] = sha256Hex(precachedBytes(url, stampedHtml, root));
  const block = `${SW_START}\nconst CACHE_VERSION = '${version}';\nconst PRECACHE = ${JSON.stringify(precache, null, 2)};\n` +
    `const INTEGRITY = ${JSON.stringify(integrity, null, 2)};\n${SW_END}`;
  const start = sw.indexOf(SW_START);
  const end = sw.indexOf(SW_END, start);
  if (start === -1 || end === -1) throw new Error('sw.js: precache markers not found');
  return sw.slice(0, start) + block + sw.slice(end + SW_END.length);
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const htmlFile = path.join(root, 'index.html');
  const swFile = path.join(root, 'sw.js');
  const html = readFileSync(htmlFile, 'utf8');
  const sw = readFileSync(swFile, 'utf8');
  const stamped = stampIndexHtml(html, root);
  const stampedSw = stampServiceWorker(sw, stamped, root);
  if (process.argv.includes('--check')) {
    if (stamped !== html || stampedSw !== sw) {
      console.error('Asset versions in index.html / sw.js are stale. Run: node scripts/stamp-assets.mjs (or `just stamp`)');
      process.exit(1);
    }
    console.log('index.html and sw.js asset versions are up to date.');
  } else if (stamped !== html || stampedSw !== sw) {
    if (stamped !== html) writeFileSync(htmlFile, stamped);
    if (stampedSw !== sw) writeFileSync(swFile, stampedSw);
    console.log(`Stamped ${listModules(root).length} modules, stylesheets, the CSP hash and the offline precache.`);
  } else {
    console.log('index.html and sw.js already up to date.');
  }
}
